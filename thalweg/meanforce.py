#!/usr/bin/env python3
"""Restrained MD at a list of points of CV space, and the mean force there.

Used twice:
  Stage 3c  at the harvested centers, to feed the free-energy map;
  Stage 6   at the images of a converged string, to feed the profile.

  setup    writes, for each point, a restraint file and a NAMD config that
           starts from that point's stored configuration, plus runs.list (one
           config per line) for the SLURM array wrapper.
  collect  reads the restraint reports, block-averages the mean force
           f = k <theta - z> = -dF/dz, and writes a centers-and-forces file
           in the format fesmap.py and cfacv's Reconstruct both read.

The NAMD base file (--namd-base) holds everything about the system and the
dynamics EXCEPT inputs, outputs, tclforces and the run command: structure,
parameters, cutoffs, PME, thermostat, barostat, timestep.

Example:
  meanforce.py setup --cv t4l_cvs.json --points centers/mesh.dat \\
      --start 'centers/center{i:05d}' --k 10 10 10 100 --steps 1000000 \\
      --namd-base base.namd --label label.pdb --cvinp cv.inp --out mf
  sbatch --account=<ask> --array=1-200%20 sbatch/namd_array.sbatch mf/runs.list
  meanforce.py collect --cv t4l_cvs.json --dir mf --out forces.dat
"""
import argparse
import os
import sys

import numpy as np

from common import CVSet, PERIODIC_TYPES, back_to_root, load_json, mean_force, read_cvout, save_json, write_forces, write_restraints

CONF = """# generated by meanforce.py: restrained MD at point {i}
# NAMD changes into the directory of its config file before reading it.  Go
# back to the directory the setup was run in: every path below, and every
# path inside the base file, is relative to that directory.
cd {root}
if {{![info exists env(CFACV_BASEDIR)]}} {{ puts "set CFACV_BASEDIR"; exit 1 }}
set CFACV_BASEDIR $env(CFACV_BASEDIR)
bincoordinates  {start}.coor
extendedSystem  {start}.xsc
{velocities}
outputname      {out}/pt{i:05d}
seed            {seed}
source          {base}
tclforces       on
tclforcesscript $CFACV_BASEDIR/tcl/cfacv_tclforces.tcl
set labelPDB        {label}
set cvINP           {cvinp}
set restrINP        {out}/restr{i:05d}.inp
set TAMDof          {every}
set TAMDoutputlevel 3
set TAMDoutputFile  {out}/pt{i:05d}.cvout
run {steps}
"""


def setup(a):
    full = CVSet.load(a.cv)
    cvs = full.subset(full.string)
    pts = np.atleast_2d(np.loadtxt(a.points))
    if pts.shape[1] != len(cvs.names):
        sys.exit(f"{a.points} has {pts.shape[1]} columns; the string has {len(cvs.names)} CVs")
    if len(a.k) != pts.shape[1]:
        sys.exit(f"--k needs {pts.shape[1]} values, one per CV, in cv.inp order")
    os.makedirs(a.out, exist_ok=True)
    nearest = None
    if a.centers:
        # start every point from the stored configuration of the center nearest
        # it: for points that are not centers themselves, such as images along
        # a route the path search found
        if not a.scales:
            sys.exit("--centers needs --scales")
        from init_string import nearest_centers
        sc = load_json(a.scales)
        if sc.get("cvs") != cvs.names:
            sys.exit(f"{a.scales}: scales are for {sc.get('cvs')}, the string CVs are {cvs.names} (same CVs in the same "
                     "order needed, or the distances to the centers mix up the CVs)")
        mesh = np.atleast_2d(np.loadtxt(os.path.join(a.centers, "mesh.dat")))
        if mesh.shape[1] != len(cvs.names):
            sys.exit(f"{a.centers}/mesh.dat has {mesh.shape[1]} columns; the string has {len(cvs.names)} CVs")
        nearest, dist = nearest_centers(pts, mesh, np.array(sc["scale"]), np.array([t in PERIODIC_TYPES for t in cvs.types]))
        nearest, dist = np.asarray(nearest, int), np.asarray(dist, float)
        print(f"each point starts from its nearest center; the farthest start is {dist.max():.2f} scaled units from its point "
              f"(median {np.median(dist):.2f}). The first part of each run is the walk there: drop it in 'collect' (--discard).")
    elif not a.start:
        sys.exit("give --start, or --centers and --scales")
    confs = []; starts = []
    for i, p in enumerate(pts):
        start = os.path.join(a.centers, f"center{nearest[i]:05d}") if nearest is not None else a.start.format(i=i)
        starts.append(start)
        for ext in (".coor", ".xsc"):
            if not os.path.exists(start + ext):
                sys.exit(f"missing {start + ext}")
        write_restraints(os.path.join(a.out, f"restr{i:05d}.inp"), p, a.k, cvs.types)
        vel = (f"binvelocities   {start}.vel" if os.path.exists(start + ".vel")
               else f"temperature     {a.temperature}")
        conf = os.path.join(a.out, f"pt{i:05d}.conf")
        with open(conf, "w") as fh:
            fh.write(CONF.format(root=back_to_root(conf), i=i, start=start, velocities=vel, out=a.out, seed=a.seed + i, base=a.namd_base,
                                 label=a.label, cvinp=a.cvinp, every=a.every, steps=a.steps))
        confs.append(conf)
    with open(os.path.join(a.out, "runs.list"), "w") as fh:
        fh.write("\n".join(confs) + "\n")
    save_json(os.path.join(a.out, "setup.json"), {"cvs": cvs.names, "types": cvs.types, "k": a.k, "points": pts, "starts": starts,
                                                  "start_from": "nearest center" if nearest is not None else "--start"})
    print(f"{len(confs)} runs set up in {a.out}/ ; submit {a.out}/runs.list as an array of 1-{len(confs)}")


def _setup(d):
    path = os.path.join(d, "setup.json")
    try:
        return load_json(path)
    except OSError:
        sys.exit(f"no {path}: not a directory written by 'meanforce.py setup'")
    except ValueError as e:
        sys.exit(f"{path} is damaged ({e})")


def collect(a):
    s = _setup(a.dir)
    periodic = np.array([t == "DIHED" for t in s["types"]])
    k = np.array(s["k"])
    z, f, se, missing = [], [], [], []
    for i in range(len(s["points"])):
        path = os.path.join(a.dir, f"pt{i:05d}.cvout")
        try:
            zi, fi, sei, _ = mean_force(read_cvout(path), k, periodic, a.discard, a.blocks)
        except (OSError, ValueError) as e:
            missing.append((i, str(e)))
            continue
        z.append(s["points"][i]); f.append(fi); se.append(sei)
    if missing:
        print(f"WARNING: {len(missing)} of {len(s['points'])} points unusable:")
        for i, e in missing[:10]:
            print(f"   point {i}: {e}")
    if not z:
        sys.exit("no usable points")
    if missing and not a.allow_missing:
        # a map or a profile with holes in it is not what was set up; leaving
        # them out has to be a decision, not a default
        sys.exit(f"{len(missing)} of {len(s['points'])} points have no usable mean force; nothing written. "
                 "Rerun them, or pass --allow-missing to write the others")
    z, f, se = np.array(z), np.array(f), np.array(se)
    write_forces(a.out, z, f, s["types"], f"mean forces from {a.dir}, k = {s['k']}")
    np.savetxt(a.out + ".se", se, fmt="%.6f", header="standard error of each mean-force component (block averages)")
    rel = np.linalg.norm(se, axis=1) / np.maximum(np.linalg.norm(f, axis=1), 1e-12)
    print(f"{len(z)} points -> {a.out}; median relative error of the mean force {np.median(rel):.3f}, "
          f"worst {rel.max():.3f}")


def metric_from_log(log, n, discard=0.2):
    """Run average of the metric tensor cfacv prints at every report
    ("CFACV) Average MT ...", each the average since the report before)."""
    rows = []
    with open(log, errors="replace") as fh:
        for line in fh:
            if line.startswith("CFACV) Average MT"):
                v = line.split()[3:]
                if len(v) == n * n:
                    rows.append([float(x) for x in v])
    if len(rows) < 5:
        raise ValueError(f"{log}: {len(rows)} metric-tensor reports")
    rows = np.array(rows[int(discard * len(rows)):])
    M = rows.mean(axis=0).reshape(n, n)
    return 0.5 * (M + M.T)


def metric(a):
    """The metric tensor at each point: averaged over the point's restrained
    run when its log is there (the default), or from the point's starting
    configuration alone (--start, with --cv and --psf)."""
    s = _setup(a.dir)
    if not a.start:
        n = len(s["cvs"]); Ms = []; pts = []; missing = 0
        for i in range(len(s["points"])):
            try:
                Ms.append(metric_from_log(os.path.join(a.dir, f"pt{i:05d}.log"), n, a.discard)); pts.append(s["points"][i])
            except (OSError, ValueError):
                missing += 1
        if not Ms:
            sys.exit(f"no metric-tensor reports in the logs under {a.dir}")
        if missing:
            print(f"WARNING: {missing} of {len(s['points'])} points have no usable log")
        s = dict(s, points=pts); Ms = np.array(Ms)
        return _write_metric(a, s, Ms, "averaged over each restrained run")
    if not (a.cv and a.psf):
        sys.exit("--start needs --cv and --psf")
    from common import CVCalculator, load_namdbin
    cvset = CVSet.load(a.cv).subset(s["cvs"])
    # each point's own starting configuration, as setup chose it: with
    # --centers that is the NEAREST center, not center i
    recorded = s.get("starts")
    if a.start == "setup":
        if not recorded:
            sys.exit(f"{a.dir}/setup.json records no starting configurations (an older setup): give --start as a path stem")
        starts = recorded
    else:
        starts = [a.start.format(i=i) for i in range(len(s["points"]))]
        if recorded and [os.path.normpath(x) for x in starts] != [os.path.normpath(x) for x in recorded]:
            k = next(i for i, (x, y) in enumerate(zip(starts, recorded)) if os.path.normpath(x) != os.path.normpath(y))
            sys.exit(f"setup started point {k} from {recorded[k]} (" + s.get("start_from", "its own start")
                     + f"), but --start would read {starts[k]}. Pass --start setup to use the configurations setup chose "
                       "(for --centers, each point's nearest center)")
    Ms = []
    for st in starts:
        u = load_namdbin(a.psf, st + ".coor")                 # with its cell, triclinic or not, when the .xsc is there
        Ms.append(CVCalculator(cvset, u).metric_tensor())
    return _write_metric(a, s, np.array(Ms), "from one configuration per point")


def _write_metric(a, s, Ms, how):
    save_json(a.out, {"cvs": s["cvs"], "points": s["points"], "M": Ms, "how": how})
    d = np.array([np.diag(M) for M in Ms])
    off = np.array([np.abs(M - np.diag(np.diag(M))).max() / np.sqrt(np.outer(np.diag(M), np.diag(M))).max() for M in Ms])
    print(f"metric tensor at {len(Ms)} points, {how} -> {a.out}")
    for n, lo, md, hi in zip(s["cvs"], d.min(0), np.median(d, 0), d.max(0)):
        print(f"   M[{n},{n}]: {lo:.4g} to {hi:.4g}, median {md:.4g}")
    print(f"   largest off-diagonal element relative to the diagonal: median {np.median(off):.2f}, worst {off.max():.2f}")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("setup")
    p.add_argument("--cv", required=True)
    p.add_argument("--points", required=True, help="one CV-space point per line (mesh.dat or a string)")
    p.add_argument("--start", help="path stem of each point's configuration, e.g. 'centers/center{i:05d}'")
    p.add_argument("--centers", help="instead of --start: the directory from harvest_centers.py; each point starts from "
                                     "the configuration of its nearest center (with --scales)")
    p.add_argument("--scales", help="scales.json (with --centers)")
    p.add_argument("--k", type=float, nargs="+", required=True, help="force constant per CV (kcal/mol per unit^2)")
    p.add_argument("--steps", type=int, required=True)
    p.add_argument("--every", type=int, default=100, help="report CVs every this many steps")
    p.add_argument("--temperature", type=float, default=300.0)
    p.add_argument("--seed", type=int, default=20261114)
    p.add_argument("--namd-base", required=True)
    p.add_argument("--label", default="label.pdb")
    p.add_argument("--cvinp", default="cv.inp")
    p.add_argument("--out", default="mf")
    p = sub.add_parser("collect")
    p.add_argument("--cv", required=False)
    p.add_argument("--dir", default="mf")
    p.add_argument("--discard", type=float, default=0.2, help="leading fraction of each run to drop")
    p.add_argument("--blocks", type=int, default=5)
    p.add_argument("--out", default="forces.dat")
    p.add_argument("--allow-missing", action="store_true", help="write the usable points even when some are not")
    p = sub.add_parser("metric", help="metric tensor at each point, for the path search (no MD)")
    p.add_argument("--dir", default="mf"); p.add_argument("--out", default="metric.json")
    p.add_argument("--discard", type=float, default=0.2, help="leading fraction of each run to drop")
    p.add_argument("--start", help="instead of the run averages, use one configuration per point: its path stem, "
                                   "as given to setup, or 'setup' for the ones setup recorded (needs --cv and --psf)")
    p.add_argument("--cv"); p.add_argument("--psf")
    a = ap.parse_args(argv)
    return {"setup": setup, "collect": collect, "metric": metric}[a.cmd](a) or 0


if __name__ == "__main__":
    sys.exit(main())
