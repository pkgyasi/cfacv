#!/usr/bin/env python3
"""Stage 4: turn a table of image anchors into a string cfacv can start from.

cfacv's string driver needs, for every MD system N,

    <root>.job0.N.coor/.vel/.xsc    its starting state
    restr.job0.N.inp                its point of CV space (the "b" values)

and reads nothing else about the initial string.  The alanine dipeptide
example produces these with a script that is fixed to a straight line in two
torsions and that drags ONE structure from image to image.  This replaces it:

  setup  takes the anchors from path_search.py (any number of CVs, any
         path), starts each image from the stored configuration of the
         nearest center, and writes a two-stage restrained warm-up for each
         system.  The warm-ups are independent, so they run in parallel.
  check  after the warm-ups, tests the Stage 4 gate: every image at its
         target, the monitored helix intact, neighbouring images
         structurally continuous.

In dual mode (two MD systems per image) system N and system N + n_images
share an anchor and a starting configuration and differ in their seed.

Example:
  init_string.py setup --cv t4l_cvs.json --anchors channels_anchors_0.dat \\
      --scales endpoints_scales.json --centers centers --k 10 10 10 100 \\
      --namd-base base.namd --out string0
  sbatch --account=<ask> --array=1-20%20 sbatch/namd_array.sbatch string0/warmup.list
  init_string.py check --cv t4l_cvs.json --dir string0 --psf t4l.psf \\
      --helix 'protein and resid 60:80'
"""
import argparse
import os
import sys

import numpy as np

from common import (CVSet, back_to_root, center_periodic, load_json, load_namdbin, read_cvout, save_json, sdist,
                    unwrap_path, wrap, write_restraints)

STAGE = """# generated by init_string.py: warm-up of system {n} (image {img}), stage {s} of {ns}, k x {frac}
# NAMD changes into the directory of its config file before reading it.  Go
# back to the directory the setup was run in: every path below, and every
# path inside the base file, is relative to that directory.
cd {root}
if {{![info exists env(CFACV_BASEDIR)]}} {{ puts "set CFACV_BASEDIR"; exit 1 }}
set CFACV_BASEDIR $env(CFACV_BASEDIR)
bincoordinates  {inp}.coor
extendedSystem  {inp}.xsc
{vel}
outputname      {outstem}
seed            {seed}
source          {base}
tclforces       on
tclforcesscript $CFACV_BASEDIR/tcl/cfacv_tclforces.tcl
set labelPDB        {label}
set cvINP           {cvinp}
set restrINP        {restr}
set TAMDof          {every}
set TAMDoutputlevel 3
set TAMDoutputFile  {cvout}
run {steps}
"""

SNIPPET = """# Lines for the string-stage configuration files (generated by init_string.py).
#
# In the system-specific stringmethod .conf:
set num_replicas {nsys}
set init_restr_file "{out}/restr.job0.%s.inp"
set initial_root "{out}/{root}"
# with cfacv's own driver:
set SMPARAMS(dual) {dual}
set SMPARAMS(zscale) {{{zscale}}}   ; # per-CV length scales for arc length
# with the thalweg driver (thalweg/driver/), the same two settings are:
set TW(dual) {dual}
set TW(zscale) {{{zscale}}}
# ... and the shared NAMD base file of the string stage must also have
#   tclforces        on
#   tclforcesscript  $CFACV_BASEDIR/tcl/cfacv_tclforces_stringmethod.tcl
#   set labelPDB ...   set cvINP ...        (TW(periodic) is read from cvINP)
# The warm-up base file used cfacv_tclforces.tcl and cannot be reused as it
# is; the driver sets langevinTemp, outputEnergies and dcdFreq itself, so
# take those out of it.  See thalweg/driver/README.md.
#
# In the shared NAMD base file, INSTEAD of "set restrPARAMS {{{{k ...}}}}":
# restrPARAMS gives every CV one harmonic force constant, which is wrong for
# CVs of different units and for a torsion near +/-180 degrees.  Point each
# replica at its own restraint file, which carries a force constant per CV
# and a PERIODIC restraint on each torsion:
set restrINP [format "{out}/restr.job0.%s.inp" [myReplica]]
"""


def nearest_centers(anchors, mesh, scale, periodic):
    idx, dist = [], []
    for a in anchors:
        d = sdist(mesh, a, scale, periodic)
        idx.append(int(d.argmin()))
        dist.append(float(d.min()))
    return idx, dist


def setup(a):
    full = CVSet.load(a.cv)
    cvs = full.subset(full.string)
    per = cvs.periodic
    sc = load_json(a.scales)
    if sc["cvs"] != cvs.names:
        sys.exit(f"scales are for {sc['cvs']}, the string CVs are {cvs.names}")
    scale = np.array(sc["scale"])
    anchors = np.atleast_2d(np.loadtxt(a.anchors))
    nd = len(cvs.names)
    if anchors.shape[1] != nd:
        sys.exit(f"{a.anchors} has {anchors.shape[1]} columns; the string has {nd} CVs")
    if len(a.k) != nd:
        sys.exit(f"--k needs {nd} values, one per CV, in cv.inp order")
    # the string must be continuous and its torsions inside the range the
    # periodic restraint handles
    anchors = center_periodic(unwrap_path(anchors, per), per)
    mesh = np.atleast_2d(np.loadtxt(os.path.join(a.centers, "mesh.dat")))
    idx, dist = nearest_centers(anchors, mesh, scale, per)
    nimg = len(anchors)
    nsys = nimg * (2 if a.dual else 1)
    os.makedirs(a.out, exist_ok=True)

    confs = []
    print(f"{'image':>5s} {'center':>6s} {'scaled distance':>15s}")
    for n in range(nsys):
        img = n % nimg
        if n < nimg:
            print(f"{img:5d} {idx[img]:6d} {dist[img]:15.2f}")
        start = os.path.join(a.centers, f"center{idx[img]:05d}")
        # the restraint file the STRING stage reads: final force constants
        write_restraints(os.path.join(a.out, f"restr.job0.{n}.inp"), anchors[img], a.k, cvs.types)
        confs.append(write_warmup(a, n, img, start, anchors[img], cvs.types))
    with open(os.path.join(a.out, "warmup.list"), "w") as fh:
        fh.write("\n".join(confs) + "\n")
    with open(os.path.join(a.out, "string_stage_snippet.namd"), "w") as fh:
        fh.write(SNIPPET.format(nsys=nsys, out=a.out, root=a.root, dual=int(a.dual),
                                zscale=" ".join(f"{v:.5f}" for v in scale)))
    np.savetxt(os.path.join(a.out, "anchors.dat"), anchors, fmt="%.6f")
    save_json(os.path.join(a.out, "setup.json"),
              {"cvs": cvs.names, "types": cvs.types, "k": a.k, "scale": scale, "anchors": anchors,
               "center": idx, "center_distance": dist, "n_images": nimg, "n_systems": nsys,
               "dual": bool(a.dual), "root": a.root})
    far = [i for i, d in enumerate(dist) if d > a.max_start_distance]
    if far:
        print(f"WARNING: images {far} start more than {a.max_start_distance} scaled units from any center; "
              "the warm-up has to drag them there")
    print(f"{nsys} warm-ups set up in {a.out}/ ; submit {a.out}/warmup.list as an array of 1-{nsys}")


def write_warmup(a, n, img, start, anchor, types):
    """Write the warm-up of one system and return the config to list.

    cfacv reads its restraint file once, when the tclforces script is loaded,
    so stepping the force constant up means one NAMD invocation per stage.
    Each stage is its own config, starting from the output of the one before.
    Only the LAST stage is listed for the array wrapper; it carries a "#PRE"
    line for each earlier stage, which the wrapper runs first, in order."""
    ns = len(a.warm_fractions)
    inp, paths = start, []
    for s, frac in enumerate(a.warm_fractions):
        last = s == ns - 1
        tag = f"warm_{n}" if last else f"warm_{n}_s{s}"
        restr = os.path.join(a.out, tag + "_restr.inp")
        write_restraints(restr, anchor, [k * frac for k in a.k], types)
        outstem = os.path.join(a.out, f"{a.root}.job0.{n}") if last else os.path.join(a.out, tag)
        path = os.path.join(a.out, tag + ".conf")
        text = STAGE.format(root=back_to_root(path), n=n, img=img, s=s + 1, ns=ns, frac=frac, inp=inp,
                            vel=(f"binvelocities   {inp}.vel" if s > 0 else f"temperature     {a.temperature}"),
                            outstem=outstem, seed=a.seed + n + 100000 * s, base=a.namd_base, label=a.label,
                            cvinp=a.cvinp, restr=restr, every=a.every, cvout=os.path.join(a.out, tag + ".cvout"),
                            steps=a.steps)
        if last:
            text = "".join(f"#PRE {q}\n" for q in paths) + text
        with open(path, "w") as fh:
            fh.write(text)
        paths.append(path)
        inp = outstem
    return paths[-1]


