def helix_fraction(u, sel, cut=3.6):
    """Fraction of i -> i+4 backbone hydrogen bonds (O...N < cut) present in
    the residues selected: 1 for an intact alpha helix."""
    res = u.select_atoms(sel).residues
    O = {r.resid: r.atoms.select_atoms("name O") for r in res}
    N = {r.resid: r.atoms.select_atoms("name N") for r in res}
    ids = sorted(O)
    pairs = [(i, i + 4) for i in ids if i + 4 in N and len(O[i]) and len(N[i + 4])]
    if not pairs:
        raise ValueError(f"helix selection '{sel}' has no i/i+4 residue pairs")
    from MDAnalysis.lib.distances import calc_bonds
    box = u.dimensions if (u.dimensions is not None and np.all(u.dimensions[:3] > 0)) else None
    d = calc_bonds(np.array([O[i].positions[0] for i, _ in pairs]), np.array([N[j].positions[0] for _, j in pairs]), box=box)
    return float(np.mean(d < cut))


def _whole(ag):
    """Positions of ag with each bonded fragment made whole across the cell
    (when there is a cell and there are bonds), else as they are."""
    box = ag.universe.dimensions
    if box is None or not np.all(box[:3] > 0):
        return ag.positions.copy()
    try:
        return ag.unwrap(compound="fragments", inplace=False).astype(float)
    except Exception:                                         # no bonds: nothing to make whole with
        return ag.positions.copy()


def check(a):
    from MDAnalysis.analysis.rms import rmsd
    path = os.path.join(a.dir, "setup.json")
    try:
        s = load_json(path)
        per = np.array([t == "DIHED" for t in s["types"]])
        scale, anchors = np.array(s["scale"]), np.array(s["anchors"])
        nimg, nsys, root = s["n_images"], s["n_systems"], s["root"]
    except OSError:
        sys.exit(f"no {path}: not a directory written by 'init_string.py setup'")
    except (ValueError, KeyError) as e:
        sys.exit(f"{path} is damaged or not from 'init_string.py setup' ({e})")
    ok_all = True

    print(f"{'system':>6s} {'image':>5s} {'offset (scaled)':>15s} {'helix':>6s} {'samples':>7s}")
    coords, offs, hel, few = [], [], [], []
    for n in range(nsys):
        img = n % nimg
        cvout = os.path.join(a.dir, f"warm_{n}.cvout")
        try:
            rep = read_cvout(cvout)
        except OSError as e:
            sys.exit(f"{cvout}: {e.strerror}; has warm-up {n} run?")
        if "Th" not in rep:
            sys.exit(f"{cvout} holds no CV values ('CFACV/C) Th' lines): the warm-up did not run, or not with TAMDoutputlevel 3")
        th = rep["Th"][1]
        if th.shape[1] != len(anchors[img]):
            sys.exit(f"{cvout} reports {th.shape[1]} CVs; the string has {len(anchors[img])}")
        th = th[len(th) // 2:]                               # second half of the last stage
        if len(th) < a.min_samples:
            few.append(n)
        d = wrap(th - anchors[img], per)
        mean = np.array([np.arctan2(np.sin(d[:, j]).mean(), np.cos(d[:, j]).mean()) if per[j] else d[:, j].mean()
                         for j in range(d.shape[1])])
        off = float(np.linalg.norm(mean / scale))
        coor = os.path.join(a.dir, f"{root}.job0.{n}.coor")
        if not os.path.exists(coor):
            sys.exit(f"no {coor}: warm-up {n} did not finish")
        try:
            u = load_namdbin(a.psf, coor)                     # with the cell beside it: NAMD may have wrapped it
        except (OSError, ValueError) as e:
            sys.exit(f"cannot read {coor} with {a.psf}: {e}")
        h = helix_fraction(u, a.helix) if a.helix else float("nan")
        fit = u.select_atoms(a.fit)
        if fit.n_atoms < 3:
            sys.exit(f"--fit '{a.fit}' matches {fit.n_atoms} atom(s) of {a.psf}: a fitted RMSD needs at least three. "
                     "Give a selection of this system's atoms (e.g. its heavy atoms).")
        coords.append(_whole(fit))
        offs.append(off); hel.append(h)
        print(f"{n:6d} {img:5d} {off:15.2f} {h:6.2f} {len(th):7d}")
    if few:
        ok_all = False
        print(f"FAIL samples: systems {few} have fewer than {a.min_samples} CV reports in the second half of the warm-up; "
              "an offset from so few says nothing (lower TAMDof or run longer)")
    bad = [n for n in range(nsys) if not offs[n] <= a.max_offset]
    if bad:
        ok_all = False
        print(f"FAIL at target: systems {bad} sit more than {a.max_offset} scaled units from their anchor")
    if a.helix:
        badh = [n for n in range(nsys) if hel[n] < a.min_helix]
        if badh:
            ok_all = False
            print(f"FAIL helix: systems {badh} have fewer than {a.min_helix:.0%} of the i/i+4 hydrogen bonds")

    # continuity: RMSD between neighbouring images (first system of each)
    r = np.array([rmsd(coords[i], coords[i + 1], superposition=True) for i in range(nimg - 1)])
    limit = a.max_jump if a.max_jump else a.jump_factor * np.median(r)
    print("neighbour RMSD (A): " + " ".join(f"{v:.2f}" for v in r))
    if not np.all(np.isfinite(r)):
        ok_all = False
        print("FAIL continuity: a neighbour RMSD is not a number")
    # a relative limit cannot see a string that has collapsed: neighbours that
    # are the same structure have a median of zero and nothing is "above" it
    same = [i for i in range(nimg - 1) if r[i] < a.min_rmsd]
    if same:
        ok_all = False
        print(f"FAIL distinct images: neighbours {[(i, i + 1) for i in same]} are less than {a.min_rmsd} A apart, the same "
              "structure: the string has collapsed, or one configuration was copied to several images")
    jumps = [i for i in range(nimg - 1) if not r[i] <= limit]
    if jumps:
        ok_all = False
        print(f"FAIL continuity: jump between images {[(i, i + 1) for i in jumps]} "
              f"(limit {limit:.2f} A = {'--max-jump' if a.max_jump else f'{a.jump_factor} x median'}). "
              "A jump means something outside the CV set differs between neighbours.")
    print(f"GATE string initiation: {'PASS' if ok_all else 'FAIL'}")
    save_json(os.path.join(a.dir, "check.json"),
              {"offset": offs, "helix": hel, "neighbour_rmsd": r, "rmsd_limit": limit, "pass": ok_all})
    return 0 if ok_all else 1


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("setup")
    p.add_argument("--cv", required=True)
    p.add_argument("--anchors", required=True, help="image anchors, one per line (from path_search.py)")
    p.add_argument("--scales", required=True)
    p.add_argument("--centers", required=True, help="directory written by harvest_centers.py")
    p.add_argument("--k", type=float, nargs="+", required=True, help="string-stage force constant per CV")
    p.add_argument("--warm-fractions", type=float, nargs="+", default=[0.1, 1.0],
                   help="warm-up stages as fractions of --k [0.1 1.0]")
    p.add_argument("--steps", type=int, default=50000, help="MD steps per warm-up stage")
    p.add_argument("--every", type=int, default=100)
    p.add_argument("--dual", action="store_true", help="two MD systems per image")
    p.add_argument("--temperature", type=float, default=300.0)
    p.add_argument("--seed", type=int, default=20261114)
    p.add_argument("--root", default="go", help="initial_root of the string run [go]")
    p.add_argument("--namd-base", required=True)
    p.add_argument("--label", default="label.pdb")
    p.add_argument("--cvinp", default="cv.inp")
    p.add_argument("--max-start-distance", type=float, default=1.5,
                   help="warn when an image starts farther than this (scaled) from its nearest center")
    p.add_argument("--out", default="string0")
    p = sub.add_parser("check")
    p.add_argument("--cv", required=False)
    p.add_argument("--dir", default="string0")
    p.add_argument("--psf", required=True)
    p.add_argument("--fit", default="protein and name CA", help="atoms for the neighbour RMSD")
    p.add_argument("--helix", default="", help="selection of the helix to monitor, e.g. 'protein and resid 60:80'")
    p.add_argument("--min-helix", type=float, default=0.7)
    p.add_argument("--max-offset", type=float, default=0.5, help="largest scaled distance of an image from its anchor")
    p.add_argument("--jump-factor", type=float, default=2.5, help="continuity limit as a multiple of the median neighbour RMSD")
    p.add_argument("--max-jump", type=float, default=0.0, help="absolute continuity limit in A (overrides the factor)")
    p.add_argument("--min-rmsd", type=float, default=0.05,
                   help="neighbouring images closer than this (A) are the same structure: a collapsed string [0.05]")
    p.add_argument("--min-samples", type=int, default=20,
                   help="fewest CV reports in the second half of a warm-up for its offset to count [20]")
    a = ap.parse_args(argv)
    if a.cmd == "setup":
        setup(a)
        return 0
    return check(a)


if __name__ == "__main__":
    sys.exit(main())
