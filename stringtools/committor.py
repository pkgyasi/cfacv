#!/usr/bin/env python3
"""Stage 7: committor test of the transition state.

  pick   takes --n evenly spaced frames from the restrained run at the image
         of highest free energy and stores them as starting configurations.
  setup  writes --shots unbiased trajectories from each configuration.  Each
         draws fresh velocities (its own seed), runs in chunks, and stops as
         soon as the string CVs enter a basin or the step cap is reached.
  tally  counts where the trajectories went and tests the gate:
           * the pooled commitment probability is 0.5 within its error;
           * the per-configuration values are consistent with ONE probability
             (a chi-square test).  A pooled 0.5 made of configurations that
             commit all one way or all the other is not a transition state;
           * few trajectories reached the cap uncommitted.  They are counted
             and reported, never dropped.

Basins are the boxes from endpoint analysis: every string CV within
nsigma standard deviations of the basin centre.

Example:
  committor.py pick --psf t4l.psf --dcd fe0/pt00009.dcd --n 10 --out ts
  committor.py setup --cv t4l_cvs.json --basins endpoints_basins.json \\
      --configs ts --shots 20 --cap-steps 2500000 --chunk 5000 \\
      --namd-base base.namd --out shots
  sbatch --account=<ask> --array=1-200%40 sbatch/namd_array.sbatch shots/runs.list
  committor.py tally --dir shots
"""
import argparse
import glob
import os
import shutil
import sys

import numpy as np

from common import CVSet, back_to_root, load_json, save_json

CONF = """# generated by committor.py: configuration {c}, shot {s}
# NAMD changes into the directory of its config file before reading it.  Go
# back to the directory the setup was run in: every path below, and every
# path inside the base file, is relative to that directory.
cd {root}
if {{![info exists env(CFACV_BASEDIR)]}} {{ puts "set CFACV_BASEDIR"; exit 1 }}
set CFACV_BASEDIR $env(CFACV_BASEDIR)
bincoordinates  {start}.coor
extendedSystem  {start}.xsc
temperature     {temperature}   ; # fresh Maxwell-Boltzmann velocities, from this shot's seed
seed            {seed}
outputname      {stem}
source          {base}
tclforces       on
tclforcesscript $CFACV_BASEDIR/tcl/cfacv_tclforces.tcl
set labelPDB        {label}
set cvINP           {cvinp}
set restrPARAMS     {{{{k 0.0}}}}  ; # measure the CVs, apply no bias
set TAMDof          {chunk}
set TAMDoutputlevel 2
set TAMDoutputFile  {stem}.cvout
set shot_chunk   {chunk}
set shot_cap     {cap}
set shot_result  {stem}.result
set basin_names  {{{names}}}
{basins}
set basin_nsigma {nsigma}
set cv_periodic  {{{periodic}}}
source {tcl}
"""


def pick(a):
    import MDAnalysis as mda
    from harvest_centers import write_xsc
    u = mda.Universe(a.psf, a.dcd)
    nf = len(u.trajectory)
    first = int(a.discard * nf)
    frames = np.unique(np.linspace(first, nf - 1, a.n).astype(int))
    if len(frames) < a.n:
        sys.exit(f"only {nf - first} usable frames for {a.n} configurations")
    os.makedirs(a.out, exist_ok=True)
    for c, fr in enumerate(frames):
        ts = u.trajectory[fr]
        u.atoms.write(os.path.join(a.out, f"config{c:02d}.coor"), file_format="NAMDBIN")
        write_xsc(os.path.join(a.out, f"config{c:02d}.xsc"), ts.dimensions)
    print(f"wrote {len(frames)} configurations (frames {list(frames)}) to {a.out}/")


def setup(a):
    full = CVSet.load(a.cv)
    cvs = full.subset(full.string)
    b = load_json(a.basins)
    if b["cvs"] != cvs.names:
        sys.exit(f"basins are for {b['cvs']}, the string CVs are {cvs.names}")
    names = [n for n in ("closed", "open") if n in b]
    basins = "\n".join(
        f"set basin_centre({n}) {{{' '.join(f'{v:.6f}' for v in b[n]['centre'])}}}\n"
        f"set basin_width({n})  {{{' '.join(f'{v:.6f}' for v in b[n]['width'])}}}" for n in names)
    configs = sorted(glob.glob(os.path.join(a.configs, "config*.coor")))
    if not configs:
        sys.exit(f"no config*.coor in {a.configs}")
    # keep the shot loop next to the configs, so the run directory is
    # self-contained and can be moved to the cluster as it is
    os.makedirs(a.out, exist_ok=True)
    tcl = os.path.join(a.out, "committor_shot.tcl")
    shutil.copy(os.path.join(os.path.dirname(os.path.abspath(__file__)), "committor_shot.tcl"), tcl)
    confs = []
    for c, coor in enumerate(configs):
        d = os.path.join(a.out, f"c{c:02d}")
        os.makedirs(d, exist_ok=True)
        for s in range(a.shots):
            stem = os.path.join(d, f"s{s:03d}")
            with open(stem + ".conf", "w") as fh:
                fh.write(CONF.format(root=back_to_root(stem + ".conf"), c=c, s=s, start=coor[:-5], temperature=a.temperature,
                                     seed=a.seed + 1000 * c + s, stem=stem, base=a.namd_base, label=a.label,
                                     cvinp=a.cvinp, chunk=a.chunk, cap=a.cap_steps, names=" ".join(names),
                                     basins=basins, nsigma=a.nsigma if a.nsigma else b["nsigma"],
                                     periodic=" ".join(str(int(p)) for p in cvs.periodic), tcl=tcl))
            confs.append(stem + ".conf")
    with open(os.path.join(a.out, "runs.list"), "w") as fh:
        fh.write("\n".join(confs) + "\n")
    save_json(os.path.join(a.out, "setup.json"),
              {"n_configs": len(configs), "shots": a.shots, "cap_steps": a.cap_steps, "basins": names})
    print(f"{len(confs)} trajectories set up in {a.out}/ ({len(configs)} configurations x {a.shots}); "
          f"submit {a.out}/runs.list as an array of 1-{len(confs)}")


def tally_counts(counts, max_uncommitted=0.2, alpha=0.05):
    """counts: list of (n_closed, n_open, n_uncommitted, n_missing) per configuration."""
    from scipy.stats import chi2
    c = np.array(counts, dtype=float)
    nA, nB, nU = c[:, 0], c[:, 1], c[:, 2]
    n = nA + nB
    with np.errstate(invalid="ignore", divide="ignore"):
        p = np.where(n > 0, nB / n, np.nan)
    N = n.sum()
    P = nB.sum() / N if N else float("nan")
    se = float(np.sqrt(P * (1 - P) / N)) if N else float("nan")
    # homogeneity: are the per-configuration values draws from one binomial?
    use = n > 0
    if 0 < P < 1 and use.sum() > 1:
        stat = float(np.sum((nB[use] - n[use] * P) ** 2 / (n[use] * P * (1 - P))))
        dof = int(use.sum() - 1)
        pval = float(chi2.sf(stat, dof))
    else:
        stat, dof, pval = float("nan"), 0, float("nan")
    unc = float(nU.sum() / (N + nU.sum())) if (N + nU.sum()) else float("nan")
    centred = bool(N > 0 and abs(P - 0.5) <= 2 * np.sqrt(0.25 / N))
    homogeneous = bool(np.isfinite(pval) and pval >= alpha)
    res = {"per_config_p_open": p, "per_config_committed": n, "pooled_p_open": float(P), "pooled_se": se,
           "committed": int(N), "uncommitted": int(nU.sum()), "missing": int(c[:, 3].sum()),
           "uncommitted_fraction": unc, "chi2": stat, "dof": dof, "p_value": pval,
           "centred": centred, "homogeneous": homogeneous, "few_uncommitted": bool(unc <= max_uncommitted)}
    res["pass"] = bool(centred and homogeneous and res["few_uncommitted"] and res["missing"] == 0)
    return res


def tally(a):
    s = load_json(os.path.join(a.dir, "setup.json"))
    A, B = s["basins"]
    counts, steps = [], []
    for c in range(s["n_configs"]):
        nA = nB = nU = nM = 0
        for sh in range(s["shots"]):
            path = os.path.join(a.dir, f"c{c:02d}", f"s{sh:03d}.result")
            if not os.path.exists(path):
                nM += 1
                continue
            w = open(path).read().split()
            steps.append(int(w[1]))
            if w[0] == A:
                nA += 1
            elif w[0] == B:
                nB += 1
            else:
                nU += 1
        counts.append((nA, nB, nU, nM))
    r = tally_counts(counts, a.max_uncommitted)
    print(f"{'config':>6s} {A:>7s} {B:>7s} {'uncomm.':>8s} {'missing':>8s} {'p(' + B + ')':>9s}")
    for c, (nA, nB, nU, nM) in enumerate(counts):
        print(f"{c:6d} {nA:7d} {nB:7d} {nU:8d} {nM:8d} {r['per_config_p_open'][c]:9.2f}")
    print(f"pooled p({B}) = {r['pooled_p_open']:.3f} +/- {r['pooled_se']:.3f} from {r['committed']} committed "
          f"trajectories; {r['uncommitted']} uncommitted ({r['uncommitted_fraction']:.1%}), {r['missing']} missing")
    if steps:
        print(f"trajectory length: median {int(np.median(steps))} steps, longest {max(steps)}")
    print(f"  centred on 0.5 within 2 standard errors : {'yes' if r['centred'] else 'NO'}")
    print(f"  configurations consistent with one value: {'yes' if r['homogeneous'] else 'NO'} "
          f"(chi-square {r['chi2']:.1f} on {r['dof']} dof, p = {r['p_value']:.3f})")
    print(f"  uncommitted fraction within {a.max_uncommitted:.0%}       : {'yes' if r['few_uncommitted'] else 'NO'}")
    if r["missing"]:
        print(f"  {r['missing']} trajectories have no result yet: the gate cannot pass until they finish")
    print(f"GATE transition state: {'PASS' if r['pass'] else 'FAIL'}")
    save_json(os.path.join(a.dir, "tally.json"), {"counts": counts, **r})
    return 0 if r["pass"] else 1


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("pick")
    p.add_argument("--psf", required=True); p.add_argument("--dcd", required=True)
    p.add_argument("--n", type=int, default=10)
    p.add_argument("--discard", type=float, default=0.2, help="leading fraction of the run to skip")
    p.add_argument("--out", default="ts")
    p = sub.add_parser("setup")
    p.add_argument("--cv", required=True)
    p.add_argument("--basins", required=True)
    p.add_argument("--configs", required=True, help="directory of config*.coor/.xsc from 'pick'")
    p.add_argument("--shots", type=int, default=20)
    p.add_argument("--cap-steps", type=int, required=True, help="step cap per trajectory")
    p.add_argument("--chunk", type=int, default=5000, help="steps between basin tests")
    p.add_argument("--nsigma", type=float, default=0.0, help="basin half-width in sd (default: from basins.json)")
    p.add_argument("--temperature", type=float, default=300.0)
    p.add_argument("--seed", type=int, default=7000000)
    p.add_argument("--namd-base", required=True)
    p.add_argument("--label", default="label.pdb")
    p.add_argument("--cvinp", default="cv.inp")
    p.add_argument("--out", default="shots")
    p = sub.add_parser("tally")
    p.add_argument("--dir", default="shots")
    p.add_argument("--max-uncommitted", type=float, default=0.2)
    a = ap.parse_args(argv)
    if a.cmd == "pick":
        pick(a); return 0
    if a.cmd == "setup":
        setup(a); return 0
    return tally(a)


if __name__ == "__main__":
    sys.exit(main())
